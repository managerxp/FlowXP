// Writes WHATSAPP_TEMPLATES.md at the repo root from the real templates (backend/src/modules/messaging/templates.js), so the text to paste into Meta is exactly what FlowXP sends.
//   node backend/scripts/whatsapp-templates-doc.mjs
import fs from 'node:fs';
import { TEMPLATES, KINDS, metaBody, CLOSING } from '../src/modules/messaging/templates.js';

const SAMPLE = {
  name: 'Asha', business: 'Red Oven Pizza House', number: 'INV-2026-00125', date: '22 Oct 2026', when: '22 Oct 2026, 3:45 pm', status: 'Paid in full', total: '₹460.00', due: '₹0', when: 'Sat 24 Oct, 6:30 pm', party: '4', minutes: '15',
  reward: 'free coffee', offer: '10% off this weekend', services: 'Haircut', plan: 'Monthly', amount: '₹1,500', code: 'GYM-0042', class: 'Morning yoga', points: '240', days: '21',
  order: 'SO-0031', invoice: 'INV-0112', vehicle: 'KA01 AB 1234', status: 'out for delivery', reply: 'Thank you for your kind words.', link: 'https://flowxp.in/bill/abc123', token: 'abc123', review: 'CabcDEF123/review'
};
// the receipt's own samples (the same word means something else in a booking)
const OWN = { name: 'Asha', business: 'Red Oven Pizza House', total: '₹460.00', number: 'INV-2026-00125', when: '22 Oct 2026, 3:45 pm', status: 'Paid in full', closing: 'We hope you enjoyed your meal.' };
const sampleOf = (kind, v) => (['BILL'].includes(kind) && v in OWN ? OWN[v] : SAMPLE[v] ?? 'Sample');
const GROUPS = [
  ['Bills and balances (every kind of business)', (k) => ['BILL', 'BALANCE_DUE', 'REVIEW_REPLY', 'LOYALTY_NEXT', 'OFFER'].includes(k)],
  ['Restaurants and cafés', (k) => k.startsWith('RESERVATION') || k.startsWith('WAITLIST')],
  ['Salons', (k) => k.startsWith('SALON_')],
  ['Gyms', (k) => k.startsWith('GYM_')],
  ['Auto parts and garages', (k) => k.startsWith('JOB_') || k === 'SERVICE_DUE'],
  ['Wholesale and distribution', (k) => k.startsWith('WS_')]
];
const lines = [];
lines.push('# WhatsApp templates FlowXP sends', '',
  'Generated by `node backend/scripts/whatsapp-templates-doc.mjs` from `backend/src/modules/messaging/templates.js`. Create each one in WhatsApp Manager, Message templates, Create template, with the **name**, **category**, **language English** and **body** below, and the samples listed. A template\'s name and variables must not change after approval.', '',
  'Category: **Utility** for everything except the ones marked **Marketing** (offers and nudges), which Meta charges more for and which only go to customers who have not opted out.', '',
  'Rules Meta enforces: no variable at the very start or end of the body; samples for every variable; no promotional wording in a Utility template.', '');
const shown = new Set();
for (const [title, test] of GROUPS) {
  lines.push(`## ${title}`, '');
  for (const kind of KINDS.filter(test)) {
    shown.add(kind);
    const t = TEMPLATES[kind];
    const body = metaBody(kind).replace(/\n/g, '\n');
    lines.push(`### \`${t.name}\` (${kind})`, '', `**Category:** ${t.promo ? 'Marketing' : 'Utility'}`, '', '**Body:**', '', '```', body, '```', '');
    lines.push(`**Samples:** ${t.vars.map((v, i) => `{{${i + 1}}} ${v} = \`${sampleOf(kind, v)}\``).join(', ')}`, '');
    if (t.urlButtons) {
      lines.push('**Buttons (Call to action, Visit website, URL type Dynamic):**', '');
      lines.push(`- \`View Invoice\`: \`https://YOUR-DOMAIN/bill/{{1}}\`, sample \`https://YOUR-DOMAIN/bill/abc123\``);
      if (t.urlButtons.length > 1) lines.push('- `Rate Us`: `https://YOUR-DOMAIN/r/{{1}}`, sample `https://YOUR-DOMAIN/r/abc123` (the Google review page of the shop; the bill when the shop has no review link)');
      lines.push('');
    }
    if (['BILL'].includes(kind)) lines.push('**Header:** none. **Footer:** `Billing powered by FlowXP`. Button texts are free: `View Bill` / `Rate Us` or `View Invoice` / `Rate Your Experience`.', '');
    if (kind === 'BILL') lines.push('One template for every shop. The Rate Us button opens the Google review page the shop saved (Settings, Business details, Google review link), or the bill when there is none.', '');
  }
}
const rest = KINDS.filter((k) => !shown.has(k));
if (rest.length) throw new Error(`Templates not in any group: ${rest.join(', ')}`);
lines.push('## The closing line of the bill (variable {{7}})', '', 'The line before "Thank you for choosing us." changes with the business. If the shop has saved its own words (Settings, receipt footer) those are used; otherwise one for its kind of business:', '', '| Business type | Line |', '|---|---|', ...Object.entries(CLOSING).map(([k, v]) => `| ${k} | ${v} |`), '');
lines.push('## Still to build (not templates in FlowXP yet)', '',
  '| Industry | Message | When it should go |', '|---|---|---|',
  '| Restaurants, cafés | Order ready (token), out for delivery | Takeaway ready; delivery rider assigned |',
  '| Hotels | Booking confirmed, check-in reminder, thank you after check-out | On booking; the day before arrival; after departure |',
  '| Pharmacies | Refill reminder, order ready | From the medicine\'s usual duration; when an order is packed |',
  '| Gaming lounges | Booking confirmed, session ending, wallet low | On booking; 10 minutes before the end; below a set balance |',
  '| Retail, supermarkets | Back in stock, offer | When a wanted item arrives; campaigns |',
  '| Gyms | Reward points (template exists, not sent yet) | When points are earned |', '');
fs.writeFileSync(new URL('../../WHATSAPP_TEMPLATES.md', import.meta.url), lines.join('\n'));
console.log(`${KINDS.length} templates written to WHATSAPP_TEMPLATES.md`);
